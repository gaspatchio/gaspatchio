"""The three hand-built examples carry the identities their own records state.

``annex_example_artifact.json`` (the supervisory annex) and section 17's two
payload examples, ``state_graph_example.json`` and
``nested_valuation_example.json``, were written by hand to show a record's
shape. No producer writes them, so nothing re-derived what they carried, and
their thirteen leaves -- the arriving columns and the one unaccounted column
-- published a ``local_fingerprint`` that was not section 12.1's digest of
the leaf's tag, name and type. Section 13 lets a consumer of either profile
recompute a leaf from exactly those three, which is what made the slip
visible: a reader taking the license would have refused the specification's
own illustrations.

They are now regenerated by this module, which owns them, and never edited by
hand where a digest is concerned. What follows from the file is taken again
with the producer's own rules: every inlined base's ``fingerprint`` from the
values it carries, read as a consumer reads them (section 13), and the name a
base with no name of its own is given after it (section 15); every leaf's
``local_fingerprint`` from its bytes, every ``fingerprint`` folded over what
the node reads, the envelope's ``graph_fingerprint`` over the pairs, the
tables and the holes, and the seal. What does not follow from the file is left
as written: these are ``audit`` documents, so a computed node, a state graph
and a nested valuation carry no tree for their ``local_fingerprint`` to be
taken over, and those digests are the illustration's own; and a base whose
values are not in the file, or are not in the form section 15 states, has no
values to take a digest over. After a deliberate change to an example, or to
the byte grammar, write them again with::

    .venv/bin/python -m tests.graph.test_hand_built_goldens
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

import pytest

from gaspatchio.frame.graph import (
    DOCUMENT_DIGEST_FIELD,
    GraphNode,
    NodeData,
    NodeType,
    document_digest_of,
    validate_artifact,
)
from gaspatchio.frame.graph.fingerprint import (
    _leaf_bytes,
    _merkle,
    _sequence,
    _text,
    selection_section,
)
from gaspatchio.frame.graph.validate import _payload_digest

_GOLDENS = Path(__file__).parent / "goldens"
HAND_BUILT = (
    "annex_example_artifact.json",
    "nested_valuation_example.json",
    "state_graph_example.json",
)

# The provenance of a column of values handed over at a line. Its bytes are
# taken over the values (section 12.1's fourth kind), not over its name and
# type, so it is no leaf even though its kind is ``input``.
_HANDED_OVER = frozenset({"injected", "continuation"})
_LEAF_KINDS = frozenset({"input", "hole", "state"})
_PREFIX = "sha256:"

# What writes the files again, named in the failure that asks for it.
_REGENERATION = ".venv/bin/python -m tests.graph.test_hand_built_goldens"


def _is_leaf(node: dict[str, Any]) -> bool:
    """Return whether section 12.1 takes ``node``'s bytes over its name and type."""
    return node["kind"] in _LEAF_KINDS and node.get("provenance") not in _HANDED_OVER


def leaf_local(node: dict[str, Any]) -> str:
    """Return a leaf's ``local_fingerprint`` as the producer takes it.

    Through the producer's own leaf bytes rather than a second reading of
    section 12.1, so that this module can only disagree with a file, never
    with the producer.
    """
    leaf = GraphNode.model_construct(
        id=node["id"],
        kind=NodeType(node["kind"]),
        data=NodeData.model_construct(column=node.get("column"), dtype=node["dtype"]),
    )
    return _PREFIX + hashlib.sha256(_leaf_bytes(leaf)).hexdigest()


def _digest(value: str) -> bytes:
    return bytes.fromhex(value.removeprefix(_PREFIX))


def payload_identity(entry: dict[str, Any]) -> str | None:
    """Return the digest an entry's inlined values hash to, or None where there are none.

    Through the reference reader's own re-hash, so that this module can only
    disagree with a file, never with the reading section 13 invites: a table
    or a join under the content grammar, a schedule or a curve under the
    recipe grammar. None for values left out (section 6.1's stand-in) and for
    values written in a form section 15 does not state.
    """
    payload = entry.get("payload")
    if not isinstance(payload, dict):
        return None
    taken, _unreadable = _payload_digest(entry.get("kind"), payload)
    return taken


def _with_payload_identities(document: dict[str, Any]) -> None:
    """Take each inlined base's ``fingerprint`` again, and follow it by name.

    A base with no name of its own is named after its identity -- its kind
    and the first eight digits of the fingerprint (section 15) -- so where the
    fingerprint moves the name moves with it, and so does every node's
    ``reads_assumptions`` entry naming it.
    """
    renamed: dict[str, str] = {}
    for entry in document["assumptions"]:
        taken = payload_identity(entry)
        if taken is None:
            continue
        name, kind = entry.get("name"), entry.get("kind")
        derived = re.fullmatch(rf"{re.escape(str(kind))}:[0-9a-f]{{8}}", str(name))
        if isinstance(name, str) and derived is not None:
            label = f"{kind}:{taken.removeprefix(_PREFIX)[:8]}"
            renamed[name] = label
            entry["name"] = label
        entry["fingerprint"] = taken
    for node in document["nodes"]:
        node["reads_assumptions"] = [
            renamed.get(read, read) for read in node.get("reads_assumptions", [])
        ]
    _follow_table_identities(
        document["nodes"],
        {
            entry["name"]: entry["fingerprint"]
            for entry in document["assumptions"]
            if entry.get("kind") == "table"
        },
    )


def _follow_table_identities(node: object, fingerprints: dict[str, str]) -> None:
    """Write each table's ``fingerprint`` into every read that names the table.

    A lookup carries its table's identity as ``table_fingerprint`` beside the
    table's name (section 11.1.24), and a section 17 state graph states its
    intensities as such trees inside its own payload. Where an inlined
    table's fingerprint is taken again, every read naming that table states
    the identity taken, wherever in the document the read is written.
    """
    if isinstance(node, list):
        for child in node:
            _follow_table_identities(child, fingerprints)
        return
    if not isinstance(node, dict):
        return
    table = node.get("table")
    if "table_fingerprint" in node and isinstance(table, str) and table in fingerprints:
        node["table_fingerprint"] = fingerprints[table]
    for child in node.values():
        _follow_table_identities(child, fingerprints)


def regenerated(document: dict[str, Any]) -> dict[str, Any]:
    """Return ``document`` with every identity that follows from it taken again.

    The inlined bases first, then the leaves, then the fold in the order the
    nodes are written -- which is the order everything a node reads comes
    before it -- then the one digest standing for the model, then the seal.
    Everything else is the document as given, key order included.
    """
    if document.get("selection"):
        msg = "a hand-built example selects no rows; this module folds no steps"
        raise ValueError(msg)
    _with_payload_identities(document)
    folded: dict[str, bytes] = {}
    for node in document["nodes"]:
        if _is_leaf(node):
            node["local_fingerprint"] = leaf_local(node)
        local = _digest(node["local_fingerprint"])
        merkle = _merkle(local, [folded[read] for read in node.get("reads", [])])
        folded[node["id"]] = merkle
        node["fingerprint"] = _PREFIX + merkle.hex()
    pairs = [_text(node_id) + folded[node_id] for node_id in sorted(folded)]
    tables = [
        _text(fingerprint)
        for fingerprint in sorted(
            {
                entry["fingerprint"]
                for entry in document["assumptions"]
                if entry.get("kind") == "table"
            }
        )
    ]
    holes = [
        _text(name) for name in sorted({hole["column"] for hole in document["holes"]})
    ]
    document["graph_fingerprint"] = (
        _PREFIX
        + hashlib.sha256(
            _sequence(pairs)
            + _sequence(tables)
            + _sequence(holes)
            + selection_section([])
        ).hexdigest()
    )
    document[DOCUMENT_DIGEST_FIELD] = document_digest_of(document)
    return document


def written(name: str) -> str:
    """Return the text this module writes for the example ``name``."""
    document = json.loads((_GOLDENS / name).read_text("utf-8"))
    return json.dumps(regenerated(document), indent=2, ensure_ascii=False) + "\n"


@pytest.mark.parametrize("name", HAND_BUILT)
def test_every_leaf_carries_the_digest_of_its_own_name_and_type(name: str) -> None:
    """Section 13's license, taken: a leaf is recomputed from either profile."""
    document = json.loads((_GOLDENS / name).read_text("utf-8"))
    leaves = [node for node in document["nodes"] if _is_leaf(node)]

    assert leaves
    assert {node["id"]: node["local_fingerprint"] for node in leaves} == {
        node["id"]: leaf_local(node) for node in leaves
    }


@pytest.mark.parametrize("name", HAND_BUILT)
def test_each_example_is_what_its_generator_writes(name: str) -> None:
    """Nothing in an example's identities was typed in."""
    assert (_GOLDENS / name).read_text("utf-8") == written(name), (
        f"{name} is not what this module writes for it. Write it again with "
        f"`{_REGENERATION}` rather than editing a digest by hand."
    )


@pytest.mark.parametrize("name", HAND_BUILT)
def test_each_example_propagates_and_seals_under_the_deep_reading(name: str) -> None:
    """Every fingerprint, the graph's, each inlined base's and the seal hold."""
    report = validate_artifact(
        json.loads((_GOLDENS / name).read_text("utf-8")), deep=True
    )
    broken = [
        f"{finding.where}: {finding.message}"
        for finding in report.findings
        if finding.severity == "error"
    ]

    assert broken == []


@pytest.mark.parametrize("name", HAND_BUILT)
def test_every_base_whose_values_are_inlined_hashes_to_its_declared_digest(
    name: str,
) -> None:
    """Each inlined base re-hashes to its ``fingerprint``, and is named after it.

    The annex's curve once declared ``sha256:5c1f0a3d…`` over values that hash
    to ``sha256:0483acfa…``, under a name taken from the wrong digest.
    """
    document = json.loads((_GOLDENS / name).read_text("utf-8"))
    declared = {
        entry["name"]: (entry["fingerprint"], payload_identity(entry))
        for entry in document["assumptions"]
        if payload_identity(entry) is not None
    }

    assert {key: taken for key, (_, taken) in declared.items()} == {
        key: stated for key, (stated, _) in declared.items()
    }
    for entry in document["assumptions"]:
        if entry["kind"] in {"schedule", "curve"}:
            assert entry["name"] == f"{entry['kind']}:{entry['fingerprint'][7:15]}"


@pytest.mark.parametrize(
    ("name", "kinds"),
    [
        ("annex_example_artifact.json", {"curve", "table"}),
        ("state_graph_example.json", {"table"}),
    ],
)
def test_every_base_an_example_inlines_is_in_the_form_its_digest_is_taken_over(
    name: str, kinds: set[str]
) -> None:
    """No base the annex or section 17's state graph inlines is an uncheckable digest.

    The state graph's two inline tables were row objects with no
    ``columns``, which no reader can re-hash, under typed-in digests.
    """
    document = json.loads((_GOLDENS / name).read_text("utf-8"))
    inlined = [
        entry
        for entry in document["assumptions"]
        if isinstance(entry.get("payload"), dict) and "omitted" not in entry["payload"]
    ]
    named = {entry["name"] for entry in document["assumptions"]}
    reads = {read for node in document["nodes"] for read in node["reads_assumptions"]}

    assert {entry["kind"] for entry in inlined} == kinds
    assert all(payload_identity(entry) is not None for entry in inlined)
    assert reads <= named


def _table_reads(node: object) -> list[tuple[str, str]]:
    """Return every ``(table, table_fingerprint)`` a document's nodes state."""
    if isinstance(node, list):
        return [read for child in node for read in _table_reads(child)]
    if not isinstance(node, dict):
        return []
    found = [read for child in node.values() for read in _table_reads(child)]
    if "table_fingerprint" in node:
        found.append((node["table"], node["table_fingerprint"]))
    return found


def test_every_digest_the_state_graph_example_declares_recomputes() -> None:
    """Section 17's state graph: each digest it states is taken over what it holds.

    The two inline tables re-hash to their entries' fingerprints; each
    intensity's ``table_fingerprint`` inside the state-graph payload is its
    table's entry; every leaf, fold, the graph fingerprint and the seal hold
    under the deep reading. Hand values: ``Table`` over the example's own
    rows stamps ``di_incidence`` ``sha256:d39ce174…`` and ``di_occ_loading``
    ``sha256:bd877d7a…``.
    """
    document = json.loads((_GOLDENS / "state_graph_example.json").read_text("utf-8"))
    entries = {entry["name"]: entry for entry in document["assumptions"]}
    reads = _table_reads(document["nodes"])
    report = validate_artifact(document, deep=True)

    assert entries["di_incidence"]["fingerprint"].startswith("sha256:d39ce1748bc68eb2")
    assert entries["di_occ_loading"]["fingerprint"].startswith(
        "sha256:bd877d7a30ea2d0d"
    )
    for name in ("di_incidence", "di_occ_loading"):
        assert payload_identity(entries[name]) == entries[name]["fingerprint"]
    assert {table for table, _ in reads} == set(entries)
    assert all(entries[table]["fingerprint"] == stated for table, stated in reads)
    assert [f.where for f in report.findings if f.severity == "error"] == []
    assert document[DOCUMENT_DIGEST_FIELD] == document_digest_of(document)


def _write_the_examples() -> None:
    """Write each hand-built example again from its own record."""
    for name in HAND_BUILT:
        (_GOLDENS / name).write_text(written(name), encoding="utf-8")


if __name__ == "__main__":
    _write_the_examples()

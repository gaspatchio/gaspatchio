# Fragment case 4a: maturity when-chain, scalar skeleton -- genuinely two-sided
#
# Every when/then/otherwise maturity check in the tutorials compares a
# per-period list column (month, duration) against a per-policy scalar
# (policy_term * 12) -- seemingly a per-fragment shape choice, but it is not
# optional: a per-period maturity test is definitionally list-vs-scalar. See
# case 4b below for why that comparison has no two-sided path today. This
# case pins the WhenThen/comparison construct itself -- cond, then, and
# otherwise all scalar -- which is the piece Col/Lit/BinOp/WhenThen already
# cover without any list-broadcast dispatch.
# =============================================================================


def test_maturity_when_chain_scalar_skeleton_reconciles() -> None:
    """A scalar when/then/otherwise (the WhenThen construct) reconciles today."""
    node = WhenThen(
        cond=BinOp(
            op="ge",
            left=Col("duration_years_at_valuation"),
            right=Col("policy_term"),
        ),
        then=Lit(0.0),
        otherwise=Col("sum_assured"),
    )
    assert_reconciles(
        "matured_flag",
        lambda af: (
            when(af.duration_years_at_valuation >= af.policy_term)
            .then(0.0)
            .otherwise(af.sum_assured)
        ),
        node,
        expect_plan_equal=True,
    )


# =============================================================================
# Fragment case 4b: maturity when-chain, real per-period form
#
# Mirrors gaspatchio/tutorials/level-3-mini-va/base/model.py lines 364-369:
# policies maturing equals survival times policy count when the elapsed
# duration in months equals the maturity month, zero otherwise -- a
# per-period (list) duration compared against a per-policy (scalar)
# maturity month.
#
# This case was proxy-only until the emission cutover, and the reason was
# recorded here in full: native Polars refuses a list-vs-scalar comparison
# for every operator, refuses a list[bool] predicate in pl.when() outright,
# and refuses to unify a list branch with a scalar one in .otherwise().
# gaspatchio's own list_conditional Rust kernel exists to route around
# exactly that gap, and lower_polars now dispatches to it -- so the node
# side computes the same per-period result the proxy side always did, and
# the case is two-sided like every other.
# =============================================================================


def test_maturity_when_chain_list_shaped_reconciles() -> None:
    """The real per-period maturity check is two-sided since the cutover.

    Also checks the shared result against an independent plain-Python
    oracle, not only against the other path: two paths agreeing on the
    wrong answer would satisfy ``assert_reconciles`` alone.
    """
    node = WhenThen(
        cond=BinOp(op="eq", left=Col("month"), right=Col("maturity_month")),
        then=BinOp(op="mul", left=Col("policies_in_force"), right=Col("sum_assured")),
        otherwise=Lit(0.0),
    )
    assert_reconciles(
        "maturity_claims",
        lambda af: (
            when(af.month == af.maturity_month)
            .then(af.policies_in_force * af.sum_assured)
            .otherwise(0.0)
        ),
        node,
    )

    oracle_af = _build_fragment_fixture()
    oracle_af.maturity_claims = (
        when(oracle_af.month == oracle_af.maturity_month)
        .then(oracle_af.policies_in_force * oracle_af.sum_assured)
        .otherwise(0.0)
    )
    result = oracle_af.collect()
    for row in result.iter_rows(named=True):
        maturity_month = row["maturity_month"]
        sum_assured = row["sum_assured"]
        expected = [
            policies * sum_assured if month == maturity_month else 0.0
            for month, policies in zip(
                row["month"], row["policies_in_force"], strict=True
            )
        ]
        assert row["maturity_claims"] == expected



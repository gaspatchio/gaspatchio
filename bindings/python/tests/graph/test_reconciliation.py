# Fragment case 1: death-claims multiply -- scalar x list broadcast
#
# Mirrors the canonical claims formula (sum_assured * deaths); L3's own
# claims_death multiplies by av_pp, which is itself list-shaped, so it is not
# a scalar-broadcast case -- sum_assured * policy_deaths is the same shape
# using L3's own column names.
# =============================================================================


def test_death_claims_scalar_times_list_reconciles() -> None:
    """death_claims = sum_assured * policy_deaths: genuinely two-sided today."""
    node = BinOp(op="mul", left=Col("sum_assured"), right=Col("policy_deaths"))
    assert_reconciles(
        "death_claims",
        lambda af: af.sum_assured * af.policy_deaths,
        node,
        expect_plan_equal=True,
    )


# =============================================================================
# Fragment case 2: monthly-rate conversion
#
# Mirrors the lapse-rate annual-to-monthly conversion at
# gaspatchio/tutorials/level-3-mini-va/base/model.py line 289: the monthly
# rate equals one minus (one minus the annual rate) raised to the 1/12
# power. lapse_rate is a scalar (constant-per-policy) column in the
# tutorial, so the exponentiation lowers to native Polars pow on a
# non-list dtype -- unlike the tutorial's *mortality* conversion (the
# mortality rate is list-shaped, from a per-period Table.lookup), native
# Polars pow does not support a list base at all (the framework's own
# list_pow plugin exists for exactly that reason).
# =============================================================================


def test_monthly_rate_conversion_reconciles() -> None:
    """lapse_rate_mth = 1 - (1 - lapse_rate) ** (1/12): genuinely two-sided today."""
    node = BinOp(
        op="sub",
        left=Lit(1),
        right=BinOp(
            op="pow",
            left=BinOp(op="sub", left=Lit(1), right=Col("lapse_rate")),
            right=Lit(1 / 12),
        ),
    )
    assert_reconciles(
        "lapse_rate_mth",
        lambda af: 1 - (1 - af.lapse_rate) ** (1 / 12),
        node,
        expect_plan_equal=True,
    )


# =============================================================================
# Fragment case 3: survival cumulative-product skeleton
#
# Mirrors gaspatchio/tutorials/level-3-mini-va/base/model.py lines 339-347:
# the combined decrement rate is one minus the product of one-minus-mortality
# and one-minus-lapse; the survival factor is one minus the combined
# decrement; cumulative survival is the running product of survival factors
# across the projection. The arithmetic skeleton (combined decrement,
# survival factor) is pure add/sub/mul over Col/Lit. The cumulative product
# itself is covered by case 3b below, now that cumulative_survival emits a
# registered Call.
# =============================================================================


def _survival_factor_via_proxy(af: ActuarialFrame) -> object:
    """Compute survival_factor via today's proxy path, mirroring the tutorial."""
    af.lapse_rate_mth = 1 - (1 - af.lapse_rate) ** (1 / 12)
    af.combined_decrement = 1.0 - (1.0 - af.mortality_rate) * (1.0 - af.lapse_rate_mth)
    return 1.0 - af.combined_decrement


def _survival_factor_node() -> OpNode:
    """Build the same survival_factor formula as an explicit op-tree, from scratch."""
    lapse_rate_mth = BinOp(
        op="sub",
        left=Lit(1),
        right=BinOp(
            op="pow",
            left=BinOp(op="sub", left=Lit(1), right=Col("lapse_rate")),
            right=Lit(1 / 12),
        ),
    )
    combined_decrement = BinOp(
        op="sub",
        left=Lit(1.0),
        right=BinOp(
            op="mul",
            left=BinOp(op="sub", left=Lit(1.0), right=Col("mortality_rate")),
            right=BinOp(op="sub", left=Lit(1.0), right=lapse_rate_mth),
        ),
    )
    return BinOp(op="sub", left=Lit(1.0), right=combined_decrement)


def test_survival_factor_arithmetic_skeleton_reconciles() -> None:
    """combined_decrement + survival_factor reconcile; the cumulation is case 3b.

    Plan equality is not asserted here: the proxy path materialises
    ``combined_decrement`` as an intermediate column and the final
    subtraction reads it back by name (via an inserted ``.repeat_by()``
    broadcast for the reflected scalar-minus-list), while the node side is
    one fully inlined tree from the raw inputs -- different shapes computing
    identical values, exactly the case value equality (not plan equality) is
    the contract for.
    """
    assert_reconciles(
        "survival_factor",
        _survival_factor_via_proxy,
        _survival_factor_node(),
    )


# =============================================================================
# Fragment case 3b: cumulative survival, both timing conventions
#
# The interior case 3 could not cover. cumulative_survival now emits
# Call("projection.cumulative_survival", ...) and its former body is a
# registered lowering, so the node side computes the cumulative product
# itself rather than stopping at the arithmetic skeleton.
#
# Both timings are covered because they are the mistake that survives
# testing: the two differ by a period at any rate, and a wrong conversion
# between them only shows once rates vary -- which they do here, since
# mortality_rate is built from attained age and moves every twelfth month.
# =============================================================================


@pytest.mark.parametrize(
    "rate_timing", ["beginning_of_period", "end_of_period"], ids=["bop", "eop"]
)
def test_cumulative_survival_reconciles(rate_timing: str) -> None:
    """The full cumulative-survival formula, node side and proxy side."""
    start_at = 1.0 if rate_timing == "beginning_of_period" else None
    node = Call(
        name="projection.cumulative_survival",
        args=(Col("mortality_rate"),),
        attrs=(("start_at", start_at), ("from_survival", False)),
    )
    assert_reconciles(
        "cumulative_survival",
        lambda af: af.mortality_rate.projection.cumulative_survival(
            rate_timing=rate_timing  # type: ignore[arg-type]
        ),
        node,
    )


def test_cumulative_survival_timings_actually_differ() -> None:
    """The two conventions must disagree here, or the case above proves nothing.

    Reconciling a formula against itself under a setting that makes no
    difference is a green test with no content. Mortality varies across
    the projection in this fixture, so beginning-of-period and
    end-of-period genuinely differ -- asserted, not assumed.
    """
    af = _build_fragment_fixture()
    af.beginning = af.mortality_rate.projection.cumulative_survival(
        rate_timing="beginning_of_period"
    )
    af.ending = af.mortality_rate.projection.cumulative_survival(
        rate_timing="end_of_period"
    )
    result = af.collect()
    assert result["beginning"].to_list()[0] != result["ending"].to_list()[0]



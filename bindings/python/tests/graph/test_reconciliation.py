# Fragment case 3f: the rollforward, on the shape it exists for
#
# A cost-of-insurance charge on the net amount at risk: the charge is
# coi_rate * (death_benefit - account_value), so the amount charged this
# period depends on the balance this period is carrying. That is the
# framework's own criterion for escalating from a closed form to a
# state-machine rollforward, and it is the one shape a cumulative product
# cannot express.
#
# This family is emission *unification* rather than relocation -- the
# kernel stays the executor and the node is the semantic record -- so the
# two-sided comparison here is between a node built by hand and the node
# the egress emits, both lowered. What it pins is that the emitted node
# names the right rollforward, the right state, and the right point; get
# any of the three wrong and the values move.
# =============================================================================


def _build_coi_rollforward() -> tuple[ActuarialFrame, object]:
    """Compile the COI-on-net-amount-at-risk rollforward on a small fixture."""
    from gaspatchio.rollforward import compile_rollforward
    from gaspatchio.schedule import Schedule

    af = ActuarialFrame(
        {
            "account_value_init": [1000.0, 2500.0],
            "death_benefit": [50_000.0, 80_000.0],
            "coi_rate": [[0.002, 0.0022, 0.0024], [0.003, 0.0032, 0.0034]],
            "premium": [[100.0, 100.0, 100.0], [150.0, 150.0, 150.0]],
            "credited_rate": [[0.004, 0.004, 0.004], [0.004, 0.004, 0.004]],
        }
    )
    af = af.projection.set(
        schedule=Schedule.from_calendar_grid(
            start_date=datetime.date(2025, 1, 31), n_periods=3, frequency="1M"
        )
    )
    builder = af.projection.rollforward(
        states={"account_value": af["account_value_init"]}, track_increments=True
    )
    (
        builder["account_value"]
        .add(af["premium"], label="Premium")
        .deduct_nar(af["coi_rate"], death_benefit=af["death_benefit"], label="COI")
        .grow(af["credited_rate"], label="Interest")
    )
    return af, compile_rollforward(builder)


def test_rollforward_coi_on_net_amount_at_risk_reconciles() -> None:
    """The state read and the increment read both reconcile, node against egress."""
    from gaspatchio.frame.lowering.rules.rollforward import operand_nodes

    af, compiled = _build_coi_rollforward()
    args = operand_nodes(compiled.ir)
    fingerprint = compiled.fingerprint()
    schedule = compiled.ir.schedule.source_sha()

    state_node = Call(
        name="rollforward.state",
        args=args,
        attrs=(
            ("fingerprint", fingerprint),
            ("schedule", schedule),
            ("state", "account_value"),
            ("point", "eop"),
            ("shared", True),
        ),
    )
    increment_node = Call(
        name="rollforward.increment",
        args=args,
        attrs=(
            ("fingerprint", fingerprint),
            ("schedule", schedule),
            ("label", "COI"),
            ("shared", True),
        ),
    )

    egress = ActuarialFrame(af.collect())
    egress.account_value = compiled.expr_for("account_value")
    egress.coi_charge = compiled.increment_for("COI")
    egress_result = egress.collect().select("account_value", "coi_charge")

    node_frame = ActuarialFrame(af.collect())
    node_frame.account_value = lower_polars(state_node, context_for(node_frame))
    node_frame.coi_charge = lower_polars(increment_node, context_for(node_frame))
    node_result = node_frame.collect().select("account_value", "coi_charge")

    assert_frame_equal(egress_result, node_result, check_exact=True)


def test_rollforward_node_shows_the_running_state_read() -> None:
    """The net-amount-at-risk charge reads the balance, and the node says so.

    ``coi_rate * (death_benefit - account_value)``: the account-value term
    is never a Polars expression anywhere -- the kernel computes it from
    the balance it carries -- so without a ``State`` child the record would
    describe a charge that reads a rate and a benefit and nothing else.
    True of the arguments, false of the calculation.

    Also checks the flat premium does *not* claim a balance read: ``Add``
    applies the same amount whatever the balance.
    """
    _, compiled = _build_coi_rollforward()
    node = compiled.expr_for("account_value")._node  # noqa: SLF001

    state_reads = [n for n in walk(node) if isinstance(n, State)]
    assert State("account_value@eop") in state_reads

    # Premium (Add) contributes its column and no state read; COI
    # (DeductNAR) and Interest (Grow) each contribute one.
    assert len(state_reads) == 2

    # A state name is not a column the frame has to supply.
    assert "account_value@eop" not in col_refs(node)
    assert "coi_rate" in col_refs(node)
    assert "death_benefit" in col_refs(node)



# =============================================================================
# assert_reconciles -- the shared two-sided helper
# =============================================================================


def assert_reconciles(
    name: str,
    build_via_proxy: Callable[[ActuarialFrame], object],
    node: OpNode,
    *,
    expect_plan_equal: bool = False,
) -> None:
    """Assert one model fragment computes identically via both paths.

    Builds two independent, freshly-constructed copies of the shared
    fragment fixture (see ``_build_fragment_fixture``). ``build_via_proxy``
    runs against the first copy exactly as a model would -- it may perform
    its own intermediate assignments -- and its returned value is assigned to
    column ``name``. ``lower_polars(node, ctx)`` is assigned to column
    ``name`` on the second, untouched copy, with ``ctx`` the second copy's
    own lowering context: the node side has to see the same column dtypes
    the proxy side does, or the two are not being asked the same question.
    Both are collected and compared with ``assert_frame_equal``: value
    equality is the contract every case here must meet.

    Plan equality (comparing ``Expr.meta.serialize()``) is a bonus, not the
    contract -- the proxy path is free to reach the same values through a
    differently-shaped plan (an intermediate column materialised instead of
    inlined, a ``.repeat_by()`` broadcast the framework inserts for a
    reflected scalar-literal op, ...). Pass ``expect_plan_equal=True`` only
    for a fragment where the plans have actually been checked to match; it
    turns a coincidence observed once into a pinned regression.

    Raises:
        AssertionError: if the two collected results differ, or if
            ``expect_plan_equal=True`` and the plans do not match.

    """
    proxy_af = _build_fragment_fixture()
    proxy_value = build_via_proxy(proxy_af)
    proxy_af[name] = proxy_value
    proxy_result = proxy_af.collect().select(name)

    node_af = _build_fragment_fixture()
    node_ctx = context_for(node_af)
    # Assigned with the node it was lowered from, as a producer hands its
    # expression back: the lowered plan bare would be an engine fragment, and
    # a table read inside one is refused because its text names no table.
    node_af[name] = ProxyAwareExpr.wrap(
        lower_polars(node, node_ctx), node=node, parent=node_af
    )
    node_result = node_af.collect().select(name)

    # check_exact=True: both sides compute from the same fixture inputs, so
    # any tolerance here would only exist to hide a genuine divergence.
    assert_frame_equal(proxy_result, node_result, check_exact=True)

    if expect_plan_equal:
        proxy_expr = to_polars_expression(proxy_value)
        node_expr = lower_polars(node, node_ctx)
        assert proxy_expr.meta.serialize() == node_expr.meta.serialize(), (
            f"{name}: plan equality was expected to hold but the two paths "
            "now build differently-shaped plans"
        )


# =============================================================================
# Fragment fixture -- shared by every assert_reconciles() case below
# =============================================================================

_FRAGMENT_SEED = 20260826
_FRAGMENT_N_POLICIES = 100
_FRAGMENT_VALUATION_DATE = datetime.date(2024, 1, 1)
_FRAGMENT_HORIZON_MONTHS = 36


def _build_fragment_fixture() -> ActuarialFrame:
    """Build the ~100-policy fixture the fragment cases reconcile against.

    Deterministic (fixed seed): every call returns a bit-identical frame, so
    ``assert_reconciles`` building two independent copies is really comparing
    apples to apples on everything except the one named column each side
    computes for itself. Carries a real monthly projection axis (3 years,
    via ``projection.set`` exactly as the tutorial does it) plus the raw
    scalar/list inputs each fragment case needs: ``mortality_rate`` and
    ``policy_deaths`` are list columns built here via the proxy path (fixture
    setup does not itself need to be two-sided -- only the one column each
    fragment case assigns does). ``maturity_month`` is drawn strictly inside
    the projection horizon so that a per-period maturity test actually fires
    for every policy -- a maturity month past the last projected month would
    make the conditional trivially all-zeros on both sides and prove
    nothing.
    """
    rng = np.random.default_rng(_FRAGMENT_SEED)
    n = _FRAGMENT_N_POLICIES
    policy_id = np.arange(1, n + 1)
    issue_age = rng.integers(30, 61, size=n)
    sum_assured = rng.uniform(50_000.0, 500_000.0, size=n).round(2)
    annual_premium = rng.uniform(500.0, 5_000.0, size=n).round(2)
    lapse_rate = rng.uniform(0.02, 0.08, size=n).round(4)
    policy_term = rng.choice([10, 15, 20], size=n)
    duration_years_at_valuation = rng.integers(0, 15, size=n)
    maturity_month = rng.integers(6, _FRAGMENT_HORIZON_MONTHS, size=n)

    af = ActuarialFrame(
        {
            "policy_id": policy_id.tolist(),
            "issue_age": issue_age.tolist(),
            "sum_assured": sum_assured.tolist(),
            "annual_premium": annual_premium.tolist(),
            "lapse_rate": lapse_rate.tolist(),
            "policy_term": policy_term.tolist(),
            "duration_years_at_valuation": duration_years_at_valuation.tolist(),
            "maturity_month": maturity_month.tolist(),
        }
    )
    af = af.projection.set(
        valuation_date=_FRAGMENT_VALUATION_DATE,
        until="term_months",
        until_value=_FRAGMENT_HORIZON_MONTHS,
        frequency="monthly",
    )
    af.attained_age = af.issue_age + af.month // 12
    af.mortality_rate = (
        (af.attained_age - 20).polars_native().cast(pl.List(pl.Float64)) * 0.0004
        + 0.001
    ).clip(0.0005, 0.35)
    af.policies_in_force = 1000.0 * (1.0 - af.mortality_rate).cum_prod()
    af.policy_deaths = af.policies_in_force * af.mortality_rate
    return af



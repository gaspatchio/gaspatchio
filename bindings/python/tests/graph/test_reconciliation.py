def _build_golden_model_points() -> ActuarialFrame:
    """~100-policy fixture matching the tutorial's own model-point schema.

    Column names and shapes mirror ``MODEL_POINTS`` in
    ``level-3-mini-va/base/model.py`` exactly, since the loaded ``main()`` is
    run unmodified against this frame. ``fund_index`` is fixed to ``"FUND1"``
    (the only fund the tutorial's inline ``INVESTMENT_RETURNS`` table
    defines) and ``issue_age`` stays within the tutorial's own inline
    mortality table's 30-99 age range across the full 20-year projection
    horizon the model always runs (``age_at_entry`` capped at 60, issue dates
    at most 10 years before the valuation date -> attained age never exceeds
    60 + 10 + 20 = 90).
    """
    rng = np.random.default_rng(_GOLDEN_SEED)
    n = _GOLDEN_N_POLICIES
    point_id = np.arange(1, n + 1)
    age_at_entry = rng.integers(30, 61, size=n)
    sex = np.where(rng.integers(0, 2, size=n) == 0, "M", "F")
    policy_term = rng.choice([5, 10, 15, 20], size=n)
    policy_count = rng.integers(50, 301, size=n)
    premium_pp = rng.uniform(20_000.0, 150_000.0, size=n).round(2)
    sum_assured = premium_pp.copy()
    av_pp_init = (premium_pp * rng.uniform(0.85, 1.20, size=n)).round(2)
    issue_year = rng.integers(2014, 2024, size=n)
    issue_month = rng.integers(1, 13, size=n)
    issue_day = rng.integers(1, 28, size=n)
    entry_date = [
        f"{year:04d}/{month:02d}/{day:02d}"
        for year, month, day in zip(issue_year, issue_month, issue_day, strict=True)
    ]
    maint_fee_rate = rng.uniform(0.010, 0.020, size=n).round(4)
    commission_rate = rng.uniform(0.02, 0.05, size=n).round(4)
    expense_acq = rng.uniform(400.0, 600.0, size=n).round(2)
    expense_maint = rng.uniform(80.0, 150.0, size=n).round(2)

    return ActuarialFrame(
        {
            "point_id": point_id.tolist(),
            "age_at_entry": age_at_entry.tolist(),
            "sex": sex.tolist(),
            "policy_term": policy_term.tolist(),
            "policy_count": policy_count.tolist(),
            "premium_pp": premium_pp.tolist(),
            "sum_assured": sum_assured.tolist(),
            "av_pp_init": av_pp_init.tolist(),
            "entry_date": entry_date,
            "fund_index": ["FUND1"] * n,
            "maint_fee_rate": maint_fee_rate.tolist(),
            "commission_rate": commission_rate.tolist(),
            "expense_acq": expense_acq.tolist(),
            "expense_maint": expense_maint.tolist(),
        }
    )


def _load_level3_model() -> ModuleType:
    """Dynamically load the tutorial's base model module by file path.

    ``level-3-mini-va`` is not a valid Python package segment (the hyphens),
    so this loads by path rather than by ``import`` -- the same idiom
    ``tests/scenarios/test_l4_aggregated_integration.py`` uses for the
    sibling L4 tutorial model.
    """
    spec = importlib.util.spec_from_file_location(
        "level3_mini_va_base_model", _LEVEL3_MODEL_PATH
    )
    if spec is None or spec.loader is None:
        msg = f"Could not load module spec from {_LEVEL3_MODEL_PATH}"
        raise ImportError(msg)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _run_golden_model() -> pl.DataFrame:
    """Run the unmodified tutorial model end to end and select the golden columns.

    Shared by the test below and by the one-off script that generated
    ``_GOLDEN_PATH``, so generation and verification can never drift apart.

    Asserts the *full* collected frame's row count and complete schema
    (name -> dtype, all 69 columns) against ``_LEVEL3_OUTPUT_SCHEMA`` before
    narrowing to ``_GOLDEN_MATERIAL_COLUMNS`` -- a schema-level cutover
    regression in any of the 61 columns the golden itself never sees (a
    column renamed, dropped, added, or changed dtype) fails here instead of
    passing silently.
    """
    model = _load_level3_model()
    af = _build_golden_model_points()
    result_af = cast("ActuarialFrame", model.main(af))
    result = result_af.collect()
    assert result.height == _GOLDEN_N_POLICIES, (
        f"expected {_GOLDEN_N_POLICIES} rows from the level-3 model, "
        f"got {result.height}"
    )
    assert dict(result.schema) == _LEVEL3_OUTPUT_SCHEMA, (
        "level-3 model's full output schema changed (a column was renamed, "
        "added, dropped, or changed dtype) -- update _LEVEL3_OUTPUT_SCHEMA "
        "if this is a deliberate change to the tutorial model"
    )
    return result.select(_GOLDEN_MATERIAL_COLUMNS)


def test_level3_full_model_reconciles_against_golden() -> None:
    """The complete level-3 tutorial model matches its checked-in golden.

    Composition-divergence gate: this runs the real, unmodified tutorial
    model end to end (mortality, lapse, account value, claims, premiums,
    expenses, commissions, discounting) rather than one fragment at a time,
    so two per-op errors that happen to offset in a single fragment case
    still show up here. See the module docstring for the golden's exact
    provenance (SHA, seed, row/column count).
    """
    actual = _run_golden_model()
    expected = pl.read_parquet(_GOLDEN_PATH)
    # check_exact=True: this golden regenerates bit-identically today, so any
    # tolerance would only exist to hide a real regression.
    assert_frame_equal(actual, expected, check_exact=True)

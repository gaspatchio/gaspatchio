"""Reconciliation harness: the safety net for the expression-emission cutover.

A formula in ``gaspatchio`` used to build its Polars expression where it
was written -- inside an operator dunder, inside the ``when``/``then``/
``otherwise`` chain, inside an accessor method. The cutover moves that
construction behind the semantic op-tree (``gaspatchio._semantic.ir``)
and ``lower_polars``, one family at a time. ``assert_reconciles`` below is
the tripwire that catches the moment the two paths disagree: it runs one
model fragment through *both* the framework's own path and an explicit
node + ``lower_polars`` construction, on two independent copies of the
same fixture, and requires the collected results to be identical.

Once a family has been cut over, the two sides are no longer independent
implementations -- the framework path lowers the same node the case
builds by hand. What the case still pins is that the *node the accessor
emits* is the node the formula means: a method that stamped the wrong
attribute, dropped an argument, or flipped a sign convention produces a
different tree from the hand-built one and the values diverge. Several
cases carry an independent plain-Python oracle as well, for exactly the
reason value-equality alone is not enough.

Two instruments:

- **Fragment cases** -- one formula at a time, sourced from
  ``gaspatchio/tutorials/level-3-mini-va/base/model.py`` (the "mini VA"
  tutorial model). Catches per-operation divergence.
- **Full-model golden** -- the complete mini VA model, run end to end on a
  deterministic 100-policy fixture, compared against a checked-in parquet
  golden. Catches composition divergence that per-fragment cases would miss
  (two offsetting per-op errors can each pass its own fragment case and still
  make the composed model wrong).

Golden provenance: ``tests/graph/goldens/level3_mini_va_golden.parquet`` was
generated by running ``gaspatchio/tutorials/level-3-mini-va/base/model.py``
unmodified, on 2026-08-26, against the 100-policy fixture built by
``_build_golden_model_points`` in this file
(seed ``20260826``). 100 rows, 8 columns (``point_id`` plus the six aggregate
present values the tutorial's own ``__main__`` block reports) -- see
``_GOLDEN_MATERIAL_COLUMNS``. Regenerated on 2026-10-10, the same way, when
``/`` over numbers became one IEEE division per element (Polars had multiplied
by a single divisor's reciprocal: the model's ``maint_fee_rate / 12.0`` and
``expense_maint / 12.0``) and a number raised to a per-period exponent became
a power per element instead of ``exp(t * ln b)`` (its inflation and discount
factors). Five present-value columns moved, in 48 rows, by at most 2.04e-15
relative (``pv_net_cf``); ``pv_premiums`` and ``pv_commissions`` did not move.
"""


# Fragment case 3e: assumption-table lookup, per-policy and per-period keys
#
# The two shapes an actuary actually writes: one rate per policy (keyed on
# issue age) and one rate per projection period (keyed on attained age,
# which moves every twelfth month). The kernel is the same either way; the
# per-period case is the one that would break if a computed key lost its
# list handling on the way into the lookup.
# =============================================================================

_LOOKUP_TABLE_NAME = "reconciliation_mortality"


def _lookup_table() -> Table:
    """Build the small mortality table both lookup cases read from.

    Ages 25-120 so the per-period case (attained age climbing over a
    three-year projection from issue ages 30-60) never misses -- a lookup
    miss raises by default, which would be a fixture bug rather than a
    reconciliation failure.
    """
    ages = list(range(25, 121))
    return Table(
        name=_LOOKUP_TABLE_NAME,
        source=pl.DataFrame(
            {
                "age": ages,
                "rate": [round(0.0005 + 0.0004 * (age - 25), 6) for age in ages],
            }
        ),
        dimensions={"age": "age"},
        value="rate",
    )


def _lookup_node(key: OpNode, table: Table) -> Call:
    """Build the lookup node by hand, with the table's own identity on it."""
    return Call(
        name="lookup",
        args=(key,),
        attrs=(
            ("table", _LOOKUP_TABLE_NAME),
            ("table_fingerprint", table._registered_sha),  # noqa: SLF001
            ("on_missing", "raise"),
            ("fill_value", None),
        ),
    )


def test_lookup_on_a_per_policy_key_reconciles() -> None:
    """One rate per policy, keyed on issue age."""
    table = _lookup_table()
    assert_reconciles(
        "issue_age_rate",
        lambda af: table.lookup(age=af.issue_age),
        _lookup_node(Col("issue_age"), table),
    )


def test_lookup_on_a_per_period_key_reconciles() -> None:
    """One rate per projection period, keyed on attained age.

    Also checked against an independent plain-Python oracle: the rate the
    table holds for the age this policy has reached in that month.
    """
    table = _lookup_table()
    attained_age = BinOp(
        op="add",
        left=Col("issue_age"),
        right=BinOp(op="floordiv", left=Col("month"), right=Lit(12)),
    )
    assert_reconciles(
        "attained_age_rate",
        lambda af: table.lookup(age=af.issue_age + af.month // 12),
        _lookup_node(attained_age, table),
    )

    oracle_af = _build_fragment_fixture()
    oracle_af.attained_age_rate = table.lookup(
        age=oracle_af.issue_age + oracle_af.month // 12
    )
    result = oracle_af.collect()
    for row in result.iter_rows(named=True):
        expected = [
            round(0.0005 + 0.0004 * (row["issue_age"] + month // 12 - 25), 6)
            for month in row["month"]
        ]
        assert row["attained_age_rate"] == pytest.approx(expected)



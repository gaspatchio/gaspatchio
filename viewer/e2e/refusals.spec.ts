/**
 * The page's refusals, read off the pages themselves.
 *
 * Every case here is a file somebody could be handed, and the thing held to in
 * each is the same: the page says one sentence naming what the file claimed,
 * and it neither guesses past the problem nor hides the sections it could still
 * draw. A page that fell back to something plausible would pass no test here,
 * because what is asserted is the sentence and not the absence of a crash.
 *
 * The files are written by this spec rather than committed. Every other fixture
 * under `fixtures/` is an export a producer wrote and a person reviewed; these
 * are edits and breakages made to provoke a refusal, and a corrupted artifact
 * sitting in a fixtures directory is a thing somebody will one day open by
 * mistake. They are written under a `refusal-` prefix, which `.gitignore`
 * ignores, and each page is packed by `pack.mjs` — the same packer, the same
 * assets, the same document `render()` writes — so what is under test is the
 * page and not a test harness's idea of one.
 *
 * Both Playwright projects run this file, so two processes may write the same
 * fixture and pack the same page at the same time. Every write here goes
 * through a temporary name and a rename, and every generated byte is a pure
 * function of the fixture it came from, so the two processes race to write
 * identical files and a reader sees one or the other whole.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { expect, test } from "@playwright/test";
import type { Page } from "@playwright/test";

import { MAX_LAYOUT_NODES } from "../src/layout/dagre";
import { exactly, formatValue } from "../src/reader/format";
import { READS_SCHEMA } from "../src/reader/types";
import type { Artifact, ArtifactNode, Edge } from "../src/reader/types";

/** One committed fixture's text. */
function text(name: string): string {
  return readFileSync(resolve(`fixtures/${name}.json`), "utf8");
}

/** One committed fixture, parsed fresh, so an edit here cannot reach another case. */
function artifact(name: string): Artifact {
  return JSON.parse(text(name)) as Artifact;
}

/** Write one fixture where a reader cannot catch it half-written. */
function writeFixture(name: string, body: string): void {
  const out = resolve(`fixtures/${name}.json`);
  const partial = `${out}.${String(process.pid)}.part`;
  writeFileSync(partial, body);
  renameSync(partial, out);
}

/**
 * Write a fixture and pack the page the exporter would have written around it.
 *
 * @param name - The fixture's name, under the ignored `refusal-` prefix.
 * @param body - Its text, which for one case here is deliberately not JSON.
 * @param second - A second artifact block to put after the first, by name.
 * @returns The packed page's `file://` URL.
 */
function packed(name: string, body: string, second?: string): string {
  writeFixture(name, body);
  const args = second === undefined ? [name] : [name, "--second", second];
  execFileSync("node", ["pack.mjs", ...args], { cwd: resolve("."), stdio: "pipe" });
  return pathToFileURL(resolve(`dist/${name}.html`)).href;
}

/**
 * What the page refused over, and the sentence it printed.
 *
 * The first of them, because one case prints its sentence in two panes: a file
 * with no values has nothing for the grid and nothing for the proof, and each
 * says so where the view would have been.
 */
async function refusal(page: Page, which: string): Promise<string> {
  const said = page.locator(`[data-testid="refusal"][data-refusal="${which}"]`).first();
  await expect(said).toBeVisible();
  return (await said.innerText()).replace(/\s+/g, " ").trim();
}

test("a schema this page does not read is named, and nothing is drawn", async ({ page }) => {
  const edited = artifact("level4");
  edited.schema = "gaspatchio-graph/v0-preview.9";
  await page.goto(packed("refusal-schema", JSON.stringify(edited)));

  const said = await refusal(page, "schema");
  expect(said).toContain("gaspatchio-graph/v0-preview.9");
  expect(said).toContain(READS_SCHEMA);
  // The seal is beside it: a reviewer holding a refused file wants to know
  // which file they are holding.
  expect(said).toContain(String(edited.document_digest));

  await expect(page.getByTestId("grid")).toHaveCount(0);
  await expect(page.getByTestId("cone")).toHaveCount(0);
});


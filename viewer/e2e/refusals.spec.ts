test("a file with no values opens, and the grid and the proof each say one line", async ({
  page,
}) => {
  // The committed copy of the published conformance corpus: `enrichment: null`
  // and not one node carrying a sample. Nothing is edited here.
  await page.goto(pathToFileURL(resolve("dist/no-values.html")).href);

  const grid = await refusal(page, "values");
  expect(grid).toContain("carries no values");
  expect(grid).toContain("--policy-id");
  await expect(page.getByTestId("grid").locator('[data-refusal="values"]')).toHaveCount(1);
  await expect(page.getByTestId("proof").locator('[data-refusal="values"]')).toHaveCount(1);

  // And the two views that read the graph rather than the frame still draw. The
  // search box is the only way in: the grid is where a column is usually picked
  // and the grid is a sentence here, which is the point — the lineage
  // is a property of the graph and survives an export with no values in it.
  await expect(page.getByTestId("inspector")).toBeVisible();
  const column = "select_loaded_claims";
  await page.getByTestId("search").fill(column);
  await page.getByTestId("search").press("Enter");
  await expect(page.getByTestId("cone-count")).toBeVisible();
  await expect(page.locator(`.react-flow__node[data-id="${column}@1"]`)).toBeVisible();
  await expect(page.getByTestId("minimap")).toBeVisible();

  // The record is there in full, values or no values.
  const record = artifact("no-values").nodes.find((node) => node.id === `${column}@1`);
  if (record === undefined) throw new Error("the no-values fixture carries no such node");
  const members = page.getByTestId("inspector").locator('[data-panel="node"] [data-member]');
  await expect(members).toHaveCount(Object.keys(record).length);
});

test("a second artifact under another fingerprint algorithm is refused, naming both", async ({
  page,
}) => {
  // The one pair `gspio diff` refuses, and so the one pair this page refuses:
  // digests taken under two byte grammars, between which there is no
  // translation. Its model file is named differently too, which is not why.
  const level4 = artifact("level4");
  const other = {
    ...artifact("level5"),
    fingerprint_algorithm: "gspv0-preview-2",
    model: { ...artifact("level5").model, source_path: "other_model.py" },
  };
  writeFixture("refusal-other-grammar", JSON.stringify(other));
  await page.goto(packed("refusal-two", text("level4"), "refusal-other-grammar"));

  const said = await refusal(page, "artifacts");
  expect(said).toContain("gspv0-preview-2");
  expect(said).toContain(level4.fingerprint_algorithm);
  expect(said).not.toContain("other_model.py");

  // The first model's page is still the page: it is the one the file named first
  // and the one every view here is drawn from. And nothing is compared — the
  // drawer has its four tabs, not the comparison's five.
  await expect(page.getByTestId("grid")).toBeVisible();
  await expect(page.getByTestId("fingerprint")).toHaveAttribute(
    "title",
    level4.graph_fingerprint,
  );
  await expect(page.locator('.inspector .tab[data-tab="changes"]')).toHaveCount(0);
});

test("a second artifact whose model file is named differently is compared, as gspio diff compares it", async ({
  page,
}) => {
  // Level 5 under its own source path: `gspio diff` compares the two, so the
  // page does too, and says what it says — lines added, removed and changed.
  const other = { ...artifact("level5"), model: { ...artifact("level5").model, source_path: "other_model.py" } };
  writeFixture("refusal-other-path", JSON.stringify(other));
  await page.goto(packed("refusal-two-paths", text("level4"), "refusal-other-path"));

  await expect(page.getByTestId("grid")).toBeVisible();
  await expect(page.locator('[data-testid="refusal"][data-refusal="artifacts"]')).toHaveCount(0);
  await expect(page.locator('.inspector .tab[data-tab="changes"]')).toHaveCount(1);
});

test("a block that is not JSON gets one sentence and the seal, lifted by regex", async ({
  page,
}) => {
  const whole = text("level1");
  const digest = String(artifact("level1").document_digest);
  // Cut after the digest, which leaves a file that carries a readable seal and
  // no closing brace — the shape a truncated download actually has.
  const truncated = whole.slice(0, whole.indexOf(digest) + digest.length + 1);
  expect(() => JSON.parse(truncated) as unknown).toThrow();
  await page.goto(packed("refusal-malformed", truncated));

  const said = await refusal(page, "json");
  expect(said).toContain("could not be read as JSON");
  expect(said).toContain(digest);
  await expect(page.getByTestId("grid")).toHaveCount(0);
});

/**
 * Level 4, grown past the count above which the whole-graph layout is skipped.
 *
 * Nodes are cloned under new ids and the edges between them re-pointed onto the
 * clones, so the graph is copies of level 4's own shape — the shape the layout
 * ceiling was measured on — and not a star or a chain. Each copy's columns are
 * named apart from the originals', because two columns of one name in one grid
 * are two columns nobody can tell apart.
 *
 * The clones carry no `value_sample` and no `trace`: they are there to make the
 * graph big, the page's values come from the originals, and copying eighty-three
 * periods of numbers four hundred and seventy-two times would make an
 * eight-megabyte fixture to prove something about a layout.
 */
function grown(to: number): Artifact {
  const base = artifact("level4");
  const nodes: ArtifactNode[] = [...base.nodes];
  const edges: Edge[] = [...base.edges];
  const suffix = (id: string, copy: number): string => `${id}~${String(copy)}`;

  for (let copy = 1; nodes.length < to; copy += 1) {
    const cloned = new Set<string>();
    for (const node of base.nodes) {
      if (nodes.length >= to) break;
      const { value_sample: _sample, trace: _trace, ...rest } = node;
      cloned.add(node.id);
      nodes.push({
        ...rest,
        id: suffix(node.id, copy),
        column: node.column === null ? null : suffix(node.column, copy),
        reads: node.reads.filter((read) => cloned.has(read)).map((read) => suffix(read, copy)),
      });
    }
    for (const edge of base.edges) {
      if (!cloned.has(edge.source) || !cloned.has(edge.target)) continue;
      edges.push({
        ...edge,
        source: suffix(edge.source, copy),
        target: suffix(edge.target, copy),
      });
    }
  }

  return { ...base, nodes, edges };
}

test("a graph too large to lay out whole still opens, and the overview says so", async ({
  page,
}) => {
  const big = grown(600);
  expect(big.nodes.length).toBe(600);
  expect(big.nodes.length).toBeGreaterThan(MAX_LAYOUT_NODES);
  await page.goto(packed("refusal-large", JSON.stringify(big)));

  // The grid works: an original column, at its own sampled value.
  await expect(page.getByTestId("grid")).toBeVisible();
  await page.getByTestId("search").fill("net_cf");
  await page.getByTestId("search").press("Enter");
  const sample = artifact("level4").nodes.find((node) => node.id === "net_cf@1")?.value_sample;
  if (!Array.isArray(sample)) throw new Error("the level-4 fixture carries no sampled net_cf@1");
  await expect(page.locator('td[data-column="net_cf"][data-period="0"]')).toHaveText(
    formatValue(sample[0]),
  );

  // The proof works: the selected column's own worked example.
  await expect(page.getByTestId("proof-idiom")).toHaveText("arithmetic");

  // And the cone opens on the window, with the overview saying what was skipped.
  await expect(page.locator('.react-flow__node[data-id="net_cf@1"]')).toBeVisible();
  const said = await refusal(page, "layout");
  expect(said).toContain("600");
  expect(said).toContain(String(MAX_LAYOUT_NODES));
  await expect(page.getByTestId("minimap")).toHaveCount(0);
});

test("a sample the trace disagrees with is flagged amber, and both are shown", async ({ page }) => {
  const edited = artifact("level4");
  const netCf = edited.nodes.find((node) => node.id === "net_cf@1");
  if (netCf === undefined || !Array.isArray(netCf.value_sample)) {
    throw new Error("the level-4 fixture carries no sampled net_cf@1");
  }
  // The trace stands at the period the export sampled it at, which is 0 on
  // every fixture this repository carries — `net_cf@1`'s trace result is
  // 49337.576616 and so is its `value_sample[0]`. Moving any other element
  // moves a number the trace never made a claim about.
  const was = netCf.value_sample[0];
  netCf.value_sample[0] = 1;
  expect(was).not.toBe(1);
  await page.goto(packed("refusal-disagreement", JSON.stringify(edited)));

  await page.getByTestId("search").fill("net_cf");
  await page.getByTestId("search").press("Enter");
  const flag = page.getByTestId("disagreement");
  await expect(flag).toBeVisible();
  // Both numbers, never reconciled: the file's two accounts of one figure,
  // each with every digit it holds, since the flag is raised on the numbers
  // and the grid's rounding could print two that differ as one.
  await expect(flag).toContainText(exactly(was) ?? "");
  await expect(flag).toContainText(exactly(1) ?? "");
});

test("a hole's own note is printed on a file with no values, where every other proof is one line", async ({
  page,
}) => {
  // The holes fixture is the committed copy of the published corpus and carries
  // no values, so the grid says its one line — and the proof used to say the
  // same line over a hole, in front of the sentence a reviewer had opened that
  // column to read. A hole's note is not about a value: the file records the
  // column as unaccounted for whether or not a policy's numbers travelled with
  // it, so the proof lets that one idiom through and refuses everything else.
  await page.goto(pathToFileURL(resolve("dist/holes.html")).href);
  const grid = await refusal(page, "values");
  expect(grid).toContain("carries no values");

  await page.getByTestId("search").fill("reserve_override");
  await page.getByTestId("search").press("Enter");
  const proof = page.getByTestId("proof");
  await expect(page.getByTestId("proof-idiom")).toHaveText("hole");
  await expect(proof.locator('[data-refusal="values"]')).toHaveCount(0);
  // The reason is the file's, read off its own holes entry rather than typed in.
  const hole = artifact("holes").holes.find(
    (entry) => (entry as { column?: unknown }).column === "reserve_override",
  ) as { reason?: unknown } | undefined;
  if (hole === undefined) throw new Error("the holes fixture records no such hole");
  await expect(proof.locator('[data-kind="note"] .text')).toHaveText(
    `reserve_override is unaccounted for: the file records it as a hole, reason "${String(hole.reason)}", and states no lineage for it. There is nothing here to work through.`,
  );

  // A column that is not a hole, on the same page, still gets the one line. A
  // per-period one, because those are the columns the search box reaches.
  await page.getByTestId("search").fill("select_loaded_claims");
  await page.getByTestId("search").press("Enter");
  await expect(page.getByTestId("proof-idiom")).toHaveCount(0);
  await expect(proof.locator('[data-refusal="values"]')).toHaveCount(1);
});

/**
 * Pack the page's JavaScript and styles.
 *
 * It writes `dist/viewer.js` and `dist/viewer.css`, and never an artifact or
 * a page. Putting a file together — bundle, styles, one artifact, one
 * favicon, one document — belongs to `gaspatchio_viewer.render()`, which is
 * what `gspio calc-graph --html` calls. Keeping the two apart means the Python
 * distribution ships built assets it did not have to reproduce, and this
 * script never needs an artifact to run.
 *
 * Fonts load as `dataurl`, so the styles carry their own faces and the exported
 * page asks the network for nothing.
 *
 * With `--copy-assets` the same build is written into the distribution's
 * package data as well, beside a `fonts.css` generated here from `fonts/`. The
 * two are one step because a copy taken separately can be a copy of a stale
 * build, and the assets in the wheel are the ones a reader opens.
 *
 * Every build also writes `third-party-notices.txt` beside the assets: each
 * npm package esbuild bundled, found from the build's own metafile, with its
 * licence file verbatim, and the font faces with theirs. `bundle.mjs` says how,
 * and refuses a bundled package that ships no licence file. The notices sit in
 * a file of their own rather than in the bundle, and `render()` puts that file
 * at the end of every page, in a comment the reader never sees.
 *
 * Printed at the end: the bytes the page costs. `gzipBytes` covers the bundle
 * and its styles together, which is what a browser is asked to fetch and what
 * the size ratchet will read.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";

import { build } from "esbuild";

import {
  bundledPackages,
  bundleOptions,
  FONT_FAMILIES,
  licenceExpression,
  thirdPartyNotices,
} from "./bundle.mjs";

const copyAssets = process.argv.includes("--copy-assets");

const result = await build({ ...bundleOptions, write: false, metafile: true });

// Every third-party package in the bundle, and the licence each built file
// carries because of them. Throws, and so fails the build, on a bundled
// package that ships no licence file.
const bundled = bundledPackages(result.metafile);

/**
 * A built file's licence, said in the file rather than about it.
 *
 * Minified output has no header of its own and REUSE reads no `.js` or `.css`
 * from the blanket annotation, so the build writes one. It travels into the
 * exported page with the asset, which is where someone holding the page rather
 * than the repository will look for it.
 *
 * The tag is spelled in two pieces. Written whole it is a tag, and the linter
 * reading this file finds `${spdx}` sitting where an expression belongs and
 * says so — it cannot know the line is a template for other files rather than a
 * claim about this one. Joining the halves at run time leaves the built files
 * carrying the tag exactly as before, and leaves this file carrying only the
 * one real tag at the top of it.
 *
 * @param spdx - The file's SPDX expression.
 * @param lines - What the expression is about, one line each.
 * @returns The header, ending in a newline.
 */
function licenceHeader(spdx, lines) {
  const tag = "SPDX-License" + "-Identifier: ";
  const body = lines.map((line) => ` * ${line}`).join("\n *\n");
  return (
    `/*!\n * SPDX-FileCopyrightText: 2026 Opio Inc.\n *\n` + ` * ${tag}${spdx}\n *\n${body}\n */\n`
  );
}

const jsHeader = licenceHeader(licenceExpression(bundled, "viewer.js"), [
  "Built from viewer/src by viewer/build.mjs.",
  "Each bundled package's notice: third-party-notices.txt, beside this file.",
]);

const cssHeader = licenceHeader(licenceExpression(bundled, "viewer.css"), [
  "Built from viewer/src by viewer/build.mjs.",
]);

// The copyright lines are FONT_FAMILIES', the same ones the notices carry.
const fontOwners = FONT_FAMILIES.map(
  ({ family, copyright }) => `${family}, ${copyright.join(", and ")}`,
).join("; ");
const fontsHeader = licenceHeader("Apache-2.0 AND OFL-1.1", [
  "Generated by viewer/build.mjs from viewer/fonts.",
  "The three faces inlined here are the documentation site's identity, not " +
    "this repository's work, and each is SIL Open Font License 1.1: " +
    `${fontOwners}${fontOwners.endsWith(".") ? "" : "."} ` +
    "The licence text is LICENSES/OFL-1.1.txt.",
]);

const js = jsHeader + (result.outputFiles.find((f) => f.path.endsWith(".js"))?.text ?? "");
const css = cssHeader + (result.outputFiles.find((f) => f.path.endsWith(".css"))?.text ?? "");

mkdirSync("dist", { recursive: true });
writeFileSync("dist/viewer.js", js);
// Written whether or not there is anything under the header. `styles()` reads
// one file by name, and a file that exists and holds only its licence says "no
// styles yet", where a missing one says "the build went wrong".
writeFileSync("dist/viewer.css", css);

/**
 * The three faces the exported page carries, as one stylesheet.
 *
 * Each is inlined `data:font/woff2;base64,…` from `fonts/`, so a page opened
 * from `file://` on a machine that has never seen these faces still renders in
 * them. Families and weights are the identity's: iA Writer
 * Quattro S at 400 and 700 for text, Zed Plex Mono at 400 for numbers,
 * formulas and code. `font-display: block` because a number drawn in a
 * fallback face is a number in the wrong tabular width.
 *
 * @returns The three `@font-face` rules, one per line.
 */
function fontsCss() {
  const faces = FONT_FAMILIES.flatMap(({ family, faces: own }) =>
    own.map(({ weight, file }) => ({ family, weight, file })),
  );
  const rules = faces
    .map(({ family, weight, file }) => {
      const base64 = readFileSync(`fonts/${file}`).toString("base64");
      return (
        `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};` +
        `font-display:block;src:url(data:font/woff2;base64,${base64}) format("woff2")}`
      );
    })
    .join("\n");
  return fontsHeader + rules;
}

// Beside the assets in dist/ and, with --copy-assets, in the wheel's package
// data, where gaspatchio-viewer ships it and lists it as a licence file.
const notices = thirdPartyNotices(bundled, FONT_FAMILIES, readFileSync("../LICENSES/OFL-1.1.txt", "utf8"));
writeFileSync("dist/third-party-notices.txt", notices);

let fontsBytes = 0;
if (copyAssets) {
  const assets = "python/gaspatchio_viewer/assets";
  mkdirSync(assets, { recursive: true });
  writeFileSync(`${assets}/viewer.js`, js);
  writeFileSync(`${assets}/viewer.css`, css);
  const fonts = fontsCss();
  writeFileSync(`${assets}/fonts.css`, fonts);
  fontsBytes = Buffer.byteLength(fonts);
  writeFileSync(`${assets}/third-party-notices.txt`, notices);
}

const jsBytes = Buffer.byteLength(js);
const cssBytes = Buffer.byteLength(css);
const gzipBytes = gzipSync(Buffer.from(js + css), { level: 9 }).length;

const thirdPartyPackages = bundled.length;

console.log(
  JSON.stringify(
    copyAssets
      ? { jsBytes, cssBytes, fontsBytes, gzipBytes, thirdPartyPackages }
      : { jsBytes, cssBytes, gzipBytes, thirdPartyPackages },
    null,
    2,
  ),
);
